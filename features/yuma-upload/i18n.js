var currentLang = localStorage.getItem('yuma_lang') || 'it';

function t(key, vars) {
  var dict = I18N[currentLang] || I18N.it;
  var s = dict[key] != null ? dict[key] : (I18N.it[key] || key);
  if (vars) {
    Object.keys(vars).forEach(function(k) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return s;
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('yuma_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  // update flag active state
  document.querySelectorAll('.lang-btn').forEach(function(btn) {
    var active = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('ring-2', active);
    btn.classList.toggle('ring-sky-400', active);
    btn.classList.toggle('opacity-100', active);
    btn.classList.toggle('opacity-50', !active);
  });
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (!key) return;
    var val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('placeholder')) el.placeholder = val;
      else el.value = val;
    } else {
      el.textContent = val;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  // re-render dynamic parts if visible
  if (typeof renderAreaSoci === 'function' && currentUser && userProfile) {
    var area = document.getElementById('area-soci');
    if (area && !area.classList.contains('hidden')) renderAreaSoci();
  }
  if (typeof renderAreaYuma === 'function' && currentUser && userProfile) {
    var areaYuma = document.getElementById('area-yuma');
    if (areaYuma && !areaYuma.classList.contains('hidden')) renderAreaYuma();
  }
}


